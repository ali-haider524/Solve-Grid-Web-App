const s=require(process.env.SG_LIB || "./build/research-statistics.js"); const d=require('./data.json'); const o={};
o.t_welch=s.independentTTest(d.g1,d.g2,true); o.t_student=s.independentTTest(d.g1,d.g2,false);
o.t_paired=s.pairedTTest(d.pre,d.post); o.t_one=s.oneSampleT(d.g1,12);
o.anova=s.oneWayAnova([{name:'a',values:d.g1},{name:'b',values:d.g2},{name:'c',values:d.g3}]);
o.chi=s.chiSquareIndependence(d.table);
o.pearson=s.correlation(d.x,d.y,'pearson'); o.spearman=s.correlation(d.x,d.y,'spearman'); o.kendall=s.correlation(d.x,d.y,'kendall');
o.mw=s.mannWhitney(d.g1,d.g2); o.wil=s.wilcoxonSignedRank(d.pre,d.post);
o.kw=s.kruskalWallis([{name:'a',values:d.g1},{name:'b',values:d.g2},{name:'c',values:d.g3}]);
o.fried=s.friedmanTest(['c1','c2','c3'],d.rm); o.shapiro=s.shapiroWilk(d.y);
o.cronbach=s.cronbachAlpha(d.items);
o.reg=s.linearRegression(['y','x','x2'],d.y.map((v,i)=>[v,d.x[i],d.x2[i]]),0,[1,2]);
o.mcn=s.mcNemarTest(30,15,4,51);
o.pz=s.pValueFromStatistic('z',1.96,'two'); o.pt=s.pValueFromStatistic('t',2.5,'two',20); o.ptr=s.pValueFromStatistic('t',2.5,'right',20); o.ptl=s.pValueFromStatistic('t',-1.3,'left',15);
o.pf=s.pValueFromStatistic('f',4.2,'right',2,27); o.pchi=s.pValueFromStatistic('chi',7.8,'right',3); o.pr=s.pValueFromStatistic('r',0.45,'two',30);
o.cimean=s.confidenceIntervalMean(50,10,25,0.95); o.ciprop=s.confidenceIntervalProportion(45,120,0.95);
o.moe1=s.marginOfError('proportion',385,0.95,{proportion:0.5}); o.moe2=s.marginOfError('proportion',278,0.95,{proportion:0.5,population:1000}); o.moe3=s.marginOfError('mean',100,0.99,{sd:12});
o.fisher=s.fisherExactTest(8,2,1,5);
o.twoway=s.twoWayAnova(d.twoway.map(r=>({a:r[0],b:r[1],y:r[2]})),'A','B');
o.rm=s.repeatedMeasuresAnova(['c1','c2','c3'],d.rm);
o.logit=s.logisticRegression(['y','x','x2'],d.logit_y.map((v,i)=>[v,d.logit_x[i],d.logit_x2[i]]),0,[1,2]);
o.omega=s.mcdonaldOmega(d.omega_items);
